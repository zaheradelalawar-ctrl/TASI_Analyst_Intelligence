def _key(name: str) -> str:
    s = _STRIP.sub(" ", name)
    s = re.sub(r"[^\w\u0600-\u06FF ]", " ", s)
    return re.sub(r"\s+", " ", s).strip().lower()


def _nospace(name: str) -> str:
    return _key(name).replace(" ", "")


def _build_index() -> dict[str, str]:
    idx: dict[str, str] = {}
    for ticker, name in SEED.items():
        idx[_key(name)] = ticker
        idx[_nospace(name)] = ticker
        idx[name.strip().lower()] = ticker
    for alias, ticker in ALIASES.items():
        idx[_key(alias)] = ticker
        idx[_nospace(alias)] = ticker
        idx[alias.strip().lower()] = ticker
    return idx


_INDEX = _build_index()


def name_to_ticker(name: str | None, known: dict[str, str] | None = None) -> str | None:
    if not name:
        return None
    raw = name.strip().lower()
    if raw in _INDEX:
        return _INDEX[raw]
    key = _key(name)
    if key in _INDEX:
        return _INDEX[key]
    nospace = _nospace(name)
    if nospace in _INDEX:
        return _INDEX[nospace]
    if known:
        for ticker, company in known.items():
            if company and _key(company) == key:
                return ticker
    for entry, ticker in _INDEX.items():
        e = entry.replace(" ", "")
        if len(e) < 5 or len(nospace) < 5:
            continue
        if e in nospace or nospace in e:
            return ticker
    return None